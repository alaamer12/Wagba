import { describe, expect, it } from "vitest";
import { pickAvatar } from "@/lib/avatar";
import { analyseName, isItLikelyFemaleName } from "@/lib/avatar-gender";
import AMBIGUOUS from "./fixtures/ambiguous-names.json";
import FEMALE from "./fixtures/female-names.json";
import MALE from "./fixtures/male-names.json";

/** Score a list: named the right gender / abstained / named the WRONG gender. */
function score(list: readonly string[], want: "male" | "female") {
  const wrong: string[] = [];
  let correct = 0;
  let abstain = 0;
  for (const name of list) {
    const g = isItLikelyFemaleName(name);
    if (g === want) correct++;
    else if (g === "unknown") abstain++;
    else wrong.push(name);
  }
  return { correct, abstain, wrong };
}

describe("isItLikelyFemaleName against the corpus", () => {
  // Floors are the measured numbers at the time this test was written —
  // 100 male: 39 named male, 61 abstain, 0 called female.
  // 100 female: 82 named female, 18 abstain, 0 called male.
  // Fixtures are data: a reviewer may add or remove a name, but a change that
  // starts CALLING A NAME THE WRONG GENDER must stay refused here.
  it("never calls a male corpus name female", () => {
    expect(score(MALE, "male").wrong).toEqual([]);
  });

  it("never calls a female corpus name male", () => {
    expect(score(FEMALE, "female").wrong).toEqual([]);
  });

  it("keeps the measured male recall", () => {
    expect(score(MALE, "male").correct).toBeGreaterThanOrEqual(39);
  });

  it("keeps the measured female recall", () => {
    expect(score(FEMALE, "female").correct).toBeGreaterThanOrEqual(82);
  });

  it("abstains on every genuinely ambiguous name", () => {
    for (const name of AMBIGUOUS) {
      expect(isItLikelyFemaleName(name), name).toBe("unknown");
    }
  });
});

describe("the first word is not the name", () => {
  const cases: Array<[string, "male" | "female" | "unknown", string]> = [
    ["مطبخ سلمى", "female", "سلمى"],
    ["مطعم كريم", "male", "كريم"],
    ["كيك منى", "female", "منى"],
    ["مأكولات أم محمد", "female", "ام"], // أم محمد = mother of: the marker carries the gender
    ["دار الضيافة", "unknown", "الضيافة"], // a shop noun, not a person — abstain is correct
    ["أبو أحمد", "male", "ابو"],
    ["محمد احمد", "male", "محمد"],
    ["Mona", "unknown", "Mona"], // Latin script carries no Arabic evidence
    ["", "unknown", ""],
  ];
  for (const [input, gender, token] of cases) {
    it(`${input || "(empty)"} → ${gender} on token "${token}"`, () => {
      const guess = analyseName(input);
      expect(guess.gender).toBe(gender);
      expect(guess.token).toBe(token);
    });
  }
});

describe("lexicon beats the suffix ladder", () => {
  // The suffix rules that would lie without the lexicon.
  it("ends-in-ى males stay male", () => {
    for (const name of ["مصطفى", "موسى", "علي", "يحيى", "مرتضى"]) {
      expect(isItLikelyFemaleName(name), name).toBe("male");
    }
  });

  it("ends-in-ي males stay male", () => {
    for (const name of ["فتحي", "شوقي", "زكي", "رامي", "هاني"]) {
      expect(isItLikelyFemaleName(name), name).toBe("male");
    }
  });

  it("ends-in-ء males stay male", () => {
    for (const name of ["ضياء", "علاء", "بهاء"]) {
      expect(isItLikelyFemaleName(name), name).toBe("male");
    }
  });

  it("ends-in-ة males stay male", () => {
    for (const name of ["حمادة", "حمزة", "أسامه"]) {
      expect(isItLikelyFemaleName(name), name).toBe("male");
    }
  });

  it("the owner's example names read right", () => {
    expect(isItLikelyFemaleName("كريم")).toBe("male");
    expect(isItLikelyFemaleName("منى")).toBe("female");
    expect(isItLikelyFemaleName("نور")).toBe("unknown");
  });

  it("is pure: the same input always gives the same answer", () => {
    expect(analyseName("مطبخ سلمى")).toEqual(analyseName("مطبخ سلمى"));
  });

  it("does not care which ya-keyboard the name was typed on", () => {
    // ى and ي at the end of a lexicon name are the same person.
    expect(isItLikelyFemaleName("على")).toBe("male");
    expect(isItLikelyFemaleName("علي")).toBe("male");
    expect(isItLikelyFemaleName("موسى")).toBe("male");
    expect(isItLikelyFemaleName("مصطفي")).toBe("male");
    expect(isItLikelyFemaleName("تقي")).toBe("unknown"); // the ambiguous set, both spellings
  });
});

describe("pickAvatar with a display name", () => {
  // The unknown case is pinned to a snapshot of the pre-change implementation
  // (scratch/avatar-before.txt, regenerated byte-identical after the change):
  // no name, a whitespace name, or an unguessable name must keep the exact
  // seeded draw — one draw per axis, untouched order.
  const SNAPSHOT: Record<string, string> = {
    mhmadhmd421: "wavy|none|round|#6e6e6e|#8f5a3c|#c9a227|#ece4f6",
    saraaebrahym183: "long|none|none|#251e19|#f3b58c|#6b8f5e|#f8e2d0",
    krymfwad907: "hijab|none|square|#251e19|#f3b58c|#c76a4a|#ece4f6",
    "probe-0": "bun|full|square|#3b312b|#f6cba8|#6b8f5e|#dce9f5",
    "probe-2": "hijab|none|round|#5b3a24|#f3b58c|#6b8f5e|#ece4f6",
    "probe-13": "bun|full|round|#3b312b|#f3b58c|#c9a227|#fcd76e",
  };
  const key = (p: ReturnType<typeof pickAvatar>) =>
    [
      p.hair,
      p.beard,
      p.glasses,
      p.hairColour,
      p.skin.skin,
      p.shirt.shirt,
      p.backdrop.backdrop,
    ].join("|");

  for (const [handle, expected] of Object.entries(SNAPSHOT)) {
    it(`keeps the seeded face for ${handle} with no name`, () => {
      expect(key(pickAvatar(handle))).toBe(expected);
      expect(key(pickAvatar(handle, "   "))).toBe(expected);
    });
  }

  it("an ambiguous name is exactly the no-name face", () => {
    expect(pickAvatar("probe-13", "نور")).toEqual(pickAvatar("probe-13"));
  });

  it("a female name never shows facial hair", () => {
    for (let i = 0; i < 60; i++) {
      expect(pickAvatar(`x-${i}`, "منى").beard, `x-${i}`).toBe("none");
    }
  });

  it("a male name never shows the hijab", () => {
    for (let i = 0; i < 60; i++) {
      expect(pickAvatar(`x-${i}`, "كريم").hair, `x-${i}`).not.toBe("hijab");
    }
  });

  it("the hijab survives for a female name that drew it", () => {
    // probe-2's raw draw is the hijab; a female name keeps it, beard cleared.
    const p = pickAvatar("probe-2", "منى");
    expect(p.hair).toBe("hijab");
    expect(p.beard).toBe("none");
  });

  it("a male name steps a drawn hijab off without shifting other axes", () => {
    const unknown = pickAvatar("probe-2");
    const male = pickAvatar("probe-2", "كريم");
    expect(male.hair).toBe("long"); // the style listed after hijab
    expect(male.glasses).toBe(unknown.glasses);
    expect(male.skin).toEqual(unknown.skin);
    expect(male.shirt).toEqual(unknown.shirt);
    expect(male.backdrop).toEqual(unknown.backdrop);
    expect(male.hairColour).toBe(unknown.hairColour);
  });
});
